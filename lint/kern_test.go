package lint_test

import (
	"bytes"
	"io/fs"
	"os"
	"strings"
	"testing"

	"kern/lint"
)

// skippedDirs are the folders a checkout of kern holds that git does not
// track: git's own, SE's, and Python's environments and caches.
var skippedDirs = map[string]bool{".git": true, ".se": true, ".venv": true, "__pycache__": true, ".pytest_cache": true, "node_modules": true}

// kernFiles answers every file of kern's checkout, as the checker reads
// them: a text file held, a binary one by its name alone.
func kernFiles(t *testing.T) []lint.File {
	t.Helper()
	var found []lint.File
	root := os.DirFS("..")
	err := fs.WalkDir(root, ".", func(name string, d fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if d.IsDir() {
			if skippedDirs[d.Name()] {
				return fs.SkipDir
			}
			return nil
		}
		if !d.Type().IsRegular() {
			return nil
		}
		data, err := fs.ReadFile(root, name)
		if err != nil {
			return err
		}
		if bytes.IndexByte(data, 0) >= 0 {
			found = append(found, lint.File{Path: name})
			return nil
		}
		found = append(found, lint.File{Path: name, Content: string(data), Held: true})
		return nil
	})
	if err != nil {
		t.Fatal(err)
	}
	return found
}

// Every file a program writes in kern carries its marker, or its line in
// .gitattributes, and kern's generated.yaml declares it: the checker's rule
// generated finds no error on kern's tree, and shows the notice on each
// generated file kern holds.
func TestKernsGeneratedFilesAreMarkedAndDeclared(t *testing.T) {
	t.Parallel()
	found := lint.Check(kernFiles(t), lint.Config{Folders: []string{"."}})
	notices := map[string]string{}
	for _, f := range found {
		if f.Rule != lint.RuleGenerated {
			continue
		}
		if !f.Notice() {
			t.Errorf("%s", f)
			continue
		}
		notices[f.Path] = f.Message
	}
	for path, want := range map[string]string{
		"mcp/testdata/door.json":                     "generated by door_test.go -golden from the MCP door's answers",
		"mcp/testdata/answers.json":                  "generated by door_test.go -golden from the MCP door's answers",
		"index/fixture/watcher.expect.recorded.json": "generated by kerntest Hot.Record from each expectation file met against its real service",
		"kerntest/testdata/names-se-or-host.txt":     "generated by moveout_test.go -update from kerntest/testdata/names-patterns.txt over kern's tree",
		"go.sum":                                     "generated by go",
	} {
		if !strings.HasPrefix(notices[path], want) {
			t.Errorf("%s shows %q, and wants %q", path, notices[path], want)
		}
	}
}
