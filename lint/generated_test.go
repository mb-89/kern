// whole hands the checker every file of the checkout, as a test of a tree does.
var whole = lint.Config{Folders: []string{"."}}

func checkWith(c lint.Config, files ...lint.File) []string {
	var got []string
	for _, f := range lint.Check(files, c) {
		got = append(got, f.String())
	}
	return got
}

// declarations declare one generator of a TOML file, a JSON file and a Go
// file, held by a test that stands.
const declarations = `# Every generator of the checkout.
generators:
  - generator: gen.py write
    source: src.txt
    outputs:
      - out.toml
      - data/*.json
      - code/**
    held_by: test_gen.py
`

// The marker is SE's wording in each comment syntax, at its place: the first
// line, or the line after a #! line, an <?xml line or Markdown front matter.
func TestTheMarkerStandsAtItsPlaceInItsSyntax(t *testing.T) {
	t.Parallel()
	if got := lint.Line("gen.py write", "src.txt", lint.Hash); got != "# Code generated by gen.py write from src.txt. DO NOT EDIT." {
		t.Fatalf("the hash marker is %q", got)
	}
	if got := lint.Line("a b", "c", lint.HTML); got != "<!-- Code generated by a b from c. DO NOT EDIT. -->" {
		t.Fatalf("the HTML marker is %q", got)
	}
	if got := lint.Attribute("door_test.go -golden"); got != "door_test.go:-golden" {
		t.Fatalf("the attribute value is %q", got)
	}
	for _, c := range []struct {
		path, content string
		at            int
	}{
		{"a.toml", "x = 1\n", 0},
		{"run", "#!/bin/sh\necho\n", 1},
		{"a.xml", "<?xml version=\"1.0\"?>\n<a/>\n", 1},
		{"a.md", "---\nname: x\n---\n\nbody\n", 3},
		{"b.md", "# Title\n", 0},
	} {
		s, ok := lint.SyntaxOf(c.path, c.content)
		if !ok {
			t.Fatalf("%s has no syntax", c.path)
		}
		marked := lint.Mark(c.content, "gen", "src", s)
		if got := lint.Place(marked, s); got != c.at {
			t.Fatalf("%s: the marker stands at line %d, and wants %d", c.path, got, c.at)
		}
		m, ok := lint.MarkerAt(marked, s)
		if !ok || m != (lint.Marker{Generator: "gen", Source: "src"}) {
			t.Fatalf("%s: the marker reads back %+v %v from\n%s", c.path, m, ok, marked)
		}
		if again := lint.Mark(marked, "gen", "src", s); again != marked {
			t.Fatalf("%s: marking twice gives\n%s", c.path, again)
		}
	}
	if _, ok := lint.SyntaxOf("a.json", "{}"); ok {
		t.Fatal("JSON has a comment syntax")
	}
}

// Every generated file the declarations name is marked, each in its own
// way, so the checker finds no error and shows each one's notice.
func TestAMarkedAndDeclaredFileShowsItsNotice(t *testing.T) {
	t.Parallel()
	got := checkWith(whole,
		held(lint.Declarations, declarations),
		held(lint.Attributes, "/data/*.json linguist-generated generated-by=gen.py:write\n"),
		held("test_gen.py", "def test(): pass\n"),
		held("out.toml", "# Code generated by gen.py write from src.txt. DO NOT EDIT.\nx = 1\n"),
		held("data/a.json", "{}\n"),
		held("code/x/y.go", "// Code generated by gen.py write from src.txt. DO NOT EDIT.\n\npackage y\n"),
		held("go.sum", "x v1 h1:y\n"),
		held("hand.md", "# By hand\n"),
	)
	expect(t, got,
		"code/x/y.go:1:1: generated notice: generated by gen.py write from src.txt; edit src.txt",
		"data/a.json:1:1: generated notice: generated by gen.py write from src.txt; edit src.txt",
		"go.sum:1:1: generated notice: generated by go; edit what it locks, then run it",
		"out.toml:1:1: generated notice: generated by gen.py write from src.txt; edit src.txt",
	)
	errs := lint.Errors(lint.Check([]lint.File{held("out.toml", "# Code generated by g from s. DO NOT EDIT.\n")}, whole))
	if len(errs) != 1 || !strings.Contains(errs[0].Message, "which generated.yaml does not declare it of") {
		t.Fatalf("a marked file in a checkout without declarations: %v", errs)
	}
}

// Each way a generated file breaks the rule is an error that names the file
// and the remedy: no marker, another generator's marker, no attributes, a
// marker no declaration covers, two declarations, a declared lock file, a
// declaration that matches nothing and a holder that does not exist.
func TestEachBreachOfTheRuleIsAnError(t *testing.T) {
	t.Parallel()
	two := declarations + `  - generator: other.py
    source: elsewhere
    outputs:
      - out.toml
      - go.sum
      - gone/*.txt
    unchecked: "no run reproduces it"
`
	got := checkWith(whole,
		held(lint.Declarations, strings.Replace(two, "test_gen.py", "test_gone.py", 1)),
		held("out.toml", "x = 1\n"),
		held("data/a.json", "{}\n"),
		held("code/a.go", "// Code generated by other.py from elsewhere. DO NOT EDIT.\npackage a\n"),
		held("code/b.go", "package b\n"),
		held("loose.yaml", "# Code generated by nobody from nothing. DO NOT EDIT.\n"),
		held("go.sum", ""),
	)
	want := []string{
		"code/a.go:1:1: generated: its marker names other.py, but generated.yaml declares it gen.py write's output; run gen.py write, or declare the file under other.py",
		"code/a.go:1:1: generated notice: generated by other.py from elsewhere; edit elsewhere",
		"code/b.go:1:1: generated: generated by gen.py write but lacks its marker `// Code generated by gen.py write from src.txt. DO NOT EDIT.`; run gen.py write, which writes it, and edit src.txt instead of the file",
		"code/b.go:1:1: generated notice: generated by gen.py write from src.txt; edit src.txt",
		"data/a.json:1:1: generated: generated by gen.py write, in a format without comments, so .gitattributes marks it: add `data/a.json linguist-generated generated-by=gen.py:write` (or a pattern that covers it)",
		"data/a.json:1:1: generated notice: generated by gen.py write from src.txt; edit src.txt",
		"generated.yaml:3:1: generated: gen.py write is held by test_gone.py, which does not exist; name the test or workflow that reruns it",
		"generated.yaml:15:1: generated: other.py declares gone/*.txt, which matches no file; remove it, or run the generator and commit what it writes",
		"go.sum:1:1: generated: go's lock file, exempt from the marker; remove it from generated.yaml",
		"loose.yaml:1:1: generated: marked as generated by nobody, which generated.yaml does not declare it of; declare it among nobody's outputs, or remove the marker from a hand-written file",
		"loose.yaml:1:1: generated notice: generated by nobody from nothing; edit nothing",
		"out.toml:1:1: generated: declared by gen.py write and other.py; one generator writes a file, so declare it once in generated.yaml",
		"out.toml:1:1: generated notice: generated by gen.py write from src.txt; edit src.txt",
	}
	expect(t, got, want...)
}

// The checker judges what it is handed: with only a managed folder, a marked
// file shows its notice, and neither a declaration whose outputs lie outside
// every managed folder nor a marked file without generated.yaml is an error.
func TestOnlyWhatTheCheckerKnowsIsJudged(t *testing.T) {
	t.Parallel()
	docs := lint.Config{Folders: []string{"docs"}}
	expect(t, checkWith(docs, held("docs/a.md", "<!-- Code generated by gen from src. DO NOT EDIT. -->\n# A\n")),
		"docs/a.md:1:1: generated notice: generated by gen from src; edit src")
	expect(t, checkWith(docs, held(lint.Declarations, declarations), held("docs/b.md", "# B\n")))
	// A file held by its hash alone shows nothing it cannot read.
	expect(t, checkWith(docs, lint.File{Path: "docs/big.go"}))
}

// generated.yaml that cannot be read is one error on its line.
func TestUnreadableDeclarationsAreOneError(t *testing.T) {
	t.Parallel()
	for _, c := range []struct{ content, want string }{
		{"generators: [", "generated.yaml:1:1: generated: generated.yaml cannot be read: yaml: line 1: did not find expected node content"},
		{"other: 1\n", "generated.yaml:1:1: generated: generated.yaml cannot be read: one key, generators, a list of generators"},
		{"generators:\n  - generator: a\n    source: b\n    outputs: [x]\n", "generated.yaml:2:1: generated: generated.yaml cannot be read: generator 1 (a): name exactly one of check, held_by and unchecked, how a fresh run is compared"},
		{"generators:\n  - generator: a\n    source: b\n    outputs: [x]\n    held_by: t\n    when: now\n", "generated.yaml:6:1: generated: generated.yaml cannot be read: generator 1: unknown key when"},
	} {
		expect(t, checkWith(whole, held(lint.Declarations, c.content)), c.want)
	}
}

// A notice fails nothing: Errors leaves it out.
func TestANoticeIsNoError(t *testing.T) {
	t.Parallel()
	found := lint.Check([]lint.File{held("go.sum", "")}, whole)
	if len(found) != 1 || !found[0].Notice() || len(lint.Errors(found)) != 0 {
		t.Fatalf("a lock file's notice: %+v", found)
	}
}
